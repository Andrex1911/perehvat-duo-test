def apply_room_zero_v9(cases):
    case = cases['room_zero']
    case['subtitle'] = 'Квартира 0 · не включайте свет'
    case['premise'] = PREMISE
    case['content_version'] = '9.0'
    case['duration'] = '45–60 минут'
    case['outcome'] = OUTCOME
    # The suspect, means and motive are intentionally unchanged. A mystery must be solvable.
    for i, beat in enumerate(BEATS):
        ch = case['chapters'][i]
        ch['title'] = beat['title']
        for role in ('a', 'b'):
            ch['tasks'][role]['objective'] = beat['title']
        ch['scene'] = beat['scene']
        ch['brief'] = beat['brief']
        ch['intro'] = [{'speaker': label, 'text': text} for label, text in beat['intro']]
        case['stages'][i]['title'] = beat['title']
        for role in ('a','b'):
            x = beat[role]
            ch['witnesses'][role] = (x['name'], x['speech'])
            ch['facts'][role] = x['fact']
            ch['evidence_titles'][role] = x['evidence_title']
            existing = ch['dialogues'][role]
            portrait = existing.get('portrait', 0 if role == 'a' else 1)
            ch['dialogues'][role] = {
                'portrait': portrait,
                'questions': [
                    {'id': 'account', 'question': 'Расскажите, что произошло.', 'answer': x['speech']},
                    {'id': 'question0', 'question': x['questions'][0][0], 'answer': x['questions'][0][1]},
                    {'id': 'question1', 'question': x['questions'][1][0], 'answer': x['questions'][1][1]},
                ],
            }
            peer = 'b' if role == 'a' else 'a'
            # Keep encrypted-in-advance puzzle conditions in the other player's personal file.
            ch['notes'][role] = (x['fact'] + '\n\nПРИЛОЖЕНИЕ ДЛЯ НАПАРНИКА\n' + ch['tasks'][peer]['_brief'])
    return cases

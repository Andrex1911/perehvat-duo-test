from copy import deepcopy

PRICES = {"episode": 99, "bundle3": 259, "all6": 499}


def l(who, text):
    return {"who": who, "text": text}


def n(id, title, lines, next=None, *, tag="СИГНАЛ", chapter="ГЛАВА", options=None, kind="dialog", **extra):
    item = {
        "id": id,
        "title": title,
        "lines": lines,
        "tag": tag,
        "chapter": chapter,
        "kind": kind,
    }
    if next is not None:
        item["next"] = next
    if options is not None:
        item["options"] = options
    item.update(extra)
    return item


def build_episode(meta, free_nodes, paid_nodes):
    gate = n(
        "gate",
        "КАНАЛ ЗАБЛОКИРОВАН",
        [
            l("СИСТЕМА", f"Первая глава эпизода «{meta['title']}» завершена."),
            l("СИСТЕМА", f"Полная история откроет ещё {len(paid_nodes)} сцен, новые решения и финалы."),
        ],
        kind="paywall",
        chapter="ПОЛНАЯ ИСТОРИЯ",
        tag=f"ОТКРЫТЬ ЗА {PRICES['episode']} ₽",
    )
    all_nodes = free_nodes + [gate] + paid_nodes
    by_id = {x["id"]: x for x in all_nodes}
    for node in all_nodes:
        if "next" in node:
            assert node["next"] in by_id, f"Broken next in {meta['id']}:{node['id']}"
        for opt in node.get("options", []):
            assert opt["next"] in by_id, f"Broken option in {meta['id']}:{node['id']}"
    meta = deepcopy(meta)
    meta.update({
        "free_start": free_nodes[0]["id"],
        "paid_start": paid_nodes[0]["id"],
        "free_gate": "gate",
        "free_scene_count": len(free_nodes),
        "scene_count": len(all_nodes),
    })
    return {"meta": meta, "free_nodes": free_nodes + [gate], "all_nodes": all_nodes}



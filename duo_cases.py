def public_catalog():
    allowed = ('id','no','title','subtitle','genre','accent','icon','premise','duration','location','area')
    return [{k: c[k] for k in allowed} for c in CASES.values()]


def task_public(t):
    public = {k: deepcopy(v) for k,v in t.items() if k != 'answer' and not k.startswith('_')}
    if t['kind']=='route': public['required_steps']=len(t['answer'].split(','))
    return public



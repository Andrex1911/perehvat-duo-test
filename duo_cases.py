from copy import deepcopy

SYMBOLS = ["◈", "△", "✦", "○", "⬡", "✚"]


def task(kind, label, answer=None, **kw):
    return {'kind': kind, 'label': label, 'answer': answer, **kw}


def spot(label, ids):
    return task('spot', label, ','.join(ids), symbols=SYMBOLS)


def code(label, digits):
    return task('code', label, str(digits))


def match(label, goal=2):
    return task('match3', label, None, goal=goal)


def radio(label, answer, options):
    return task('radio', label, answer, options=options)


def timeline(label, answer, events):
    return task('timeline', label, ','.join(answer), events=events)


def route(label, answer, places):
    return task('route', label, ','.join(answer), places=places)


def circuit(label, contacts):
    return task('circuit', label, ','.join(contacts), contacts=['A1','A2','A3','B1','B2','B3'])


def chapter(title, scene, brief, place_a, place_b, witness_a, witness_b, task_a, task_b, a_note, b_note):
    return {
      'title': title, 'scene': scene, 'brief': brief,
      'locations': {'a': place_a, 'b': place_b},
      'witnesses': {'a': witness_a, 'b': witness_b},
      'tasks': {'a': task_a, 'b': task_b},
      'notes': {'a': a_note, 'b': b_note},
    }


